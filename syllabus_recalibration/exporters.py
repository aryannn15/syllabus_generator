def export_docx(
    result: RedistributionResult,
    narrative: str = "",
    path: Optional[str] = None,
    output_dir: str = OUTPUT_DIR,
) -> str:
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor, Inches
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.oxml.ns import qn
        from docx.oxml import OxmlElement
    except ImportError:
        raise ImportError("python-docx is required: pip install python-docx")

    out = path or os.path.join(_ensure_output_dir(output_dir), "recalibrated_syllabus.docx")

    doc = Document()

    # Title
    title = doc.add_heading("Adaptive Syllabus Recalibration Report", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Narrative
    if narrative:
        doc.add_heading("Summary", level=1)
        para = doc.add_paragraph(narrative)
        para.style.font.size = Pt(11)

    # Table
    doc.add_heading("Recalibrated Module Hours", level=1)

    headers = [
        "#", "Module", "Original (h)", "Recalibrated (h)", "Delta",
        "PYQ Score", "Difficulty", "Importance"
    ]
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"

    # Header row
    hdr_row = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_row[i].text = h
        run = hdr_row[i].paragraphs[0].runs[0]
        run.bold = True
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        # Dark blue cell background
        tc = hdr_row[i]._tc
        tcPr = tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:fill"), "0F3460")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:val"), "clear")
        tcPr.append(shd)

    orig_sorted  = sorted(result.original_modules,     key=lambda m: m.module_id)
    recal_sorted = sorted(result.recalibrated_modules, key=lambda m: m.module_id)

    total_orig  = 0.0
    total_recal = 0.0

    for orig, recal in zip(orig_sorted, recal_sorted):
        delta = recal.allocated_hours - orig.original_hours
        total_orig  += orig.original_hours
        total_recal += recal.allocated_hours

        delta_str = f"+{delta:.2f}h" if delta > 0.01 else (
            f"{delta:.2f}h" if delta < -0.01 else "—"
        )

        row = table.add_row().cells
        row[0].text = str(orig.module_id)
        row[1].text = orig.module_name
        row[2].text = f"{orig.original_hours:.2f}h"
        row[3].text = f"{recal.allocated_hours:.2f}h"
        row[4].text = delta_str
        row[5].text = f"{orig.pyq_score:.4f}"
        row[6].text = recal.difficulty.value
        row[7].text = recal.importance.value

    # Totals row
    tot_row = table.add_row().cells
    tot_row[0].text = ""
    tot_row[1].text = "TOTAL"
    tot_row[2].text = f"{total_orig:.2f}h"
    tot_row[3].text = f"{total_recal:.2f}h"
    for cell in tot_row:
        for para in cell.paragraphs:
            for run in para.runs:
                run.bold = True

    # Warnings
    if result.warnings:
        doc.add_heading("Warnings", level=1)
        for w in result.warnings:
            doc.add_paragraph(f"⚠ {w}", style="List Bullet")

    # Log
    if result.adjustment_log:
        doc.add_heading("Adjustment Log", level=1)
        for entry in result.adjustment_log:
            doc.add_paragraph(entry, style="List Bullet")

    doc.save(out)
    print(f"[exporter] DOCX → {out}")
    return out


# ---------------------------------------------------------------------------
# Convenience: export all formats
# ---------------------------------------------------------------------------

def export_all(
    result: RedistributionResult,
    narrative: str = "",
    formats: List[str] = None,
    output_dir: str = OUTPUT_DIR,
) -> dict:
    formats = formats or ["csv", "html", "docx"]
    paths = {}
    if "csv"  in formats: paths["csv"]  = export_csv(result, output_dir=output_dir)
    if "html" in formats: paths["html"] = export_html(result, narrative, output_dir=output_dir)
    if "pdf"  in formats: paths["pdf"]  = export_pdf(result, narrative, output_dir=output_dir)
    if "docx" in formats: paths["docx"] = export_docx(result, narrative, output_dir=output_dir)
    return paths