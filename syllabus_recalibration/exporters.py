def export_html(
    result: RedistributionResult,
    narrative: str = "",
    path: Optional[str] = None,
    output_dir: str = OUTPUT_DIR,
) -> str:
    out = path or os.path.join(_ensure_output_dir(output_dir), "recalibrated_syllabus.html")

    orig_sorted  = sorted(result.original_modules,     key=lambda m: m.module_id)
    recal_sorted = sorted(result.recalibrated_modules, key=lambda m: m.module_id)

    row_html = ""
    total_orig  = 0.0
    total_recal = 0.0

    for orig, recal in zip(orig_sorted, recal_sorted):
        delta = recal.allocated_hours - orig.original_hours
        total_orig  += orig.original_hours
        total_recal += recal.allocated_hours

        if delta > 0.01:
            delta_str = f'<span class="pos">+{delta:.2f}h</span>'
        elif delta < -0.01:
            delta_str = f'<span class="neg">{delta:.2f}h</span>'
        else:
            delta_str = f'<span class="zero">—</span>'

        row_html += (
            f"<tr>"
            f"<td>{orig.module_id}</td>"
            f"<td><strong>{orig.module_name}</strong><br>"
            f"<small style='color:#666'>{'; '.join(orig.topics)}</small></td>"
            f"<td>{orig.original_hours:.2f}h</td>"
            f"<td>{recal.allocated_hours:.2f}h</td>"
            f"<td>{delta_str}</td>"
            f"<td>{orig.pyq_score:.4f}</td>"
            f"<td>{recal.difficulty.value}</td>"
            f"<td>{recal.importance.value}</td>"
            f"</tr>\n"
        )

    narrative_section = ""
    if narrative:
        narrative_section = (
            f"<h2>Summary</h2>"
            f'<div class="narrative">{narrative}</div>'
        )

    warnings_section = ""
    if result.warnings:
        warns = "".join(f'<div class="warn">⚠ {w}</div>' for w in result.warnings)
        warnings_section = f"<h2>Warnings</h2>{warns}"

    log_section = ""
    if result.adjustment_log:
        logs = "".join(f'<div class="log">{l}</div>' for l in result.adjustment_log)
        log_section = f"<h2>Adjustment Log</h2>{logs}"

    html = _HTML_TEMPLATE.format(
        rows=row_html,
        total_orig=total_orig,
        total_recal=total_recal,
        narrative_section=narrative_section,
        warnings_section=warnings_section,
        log_section=log_section,
    )

    with open(out, "w", encoding="utf-8") as f:
        f.write(html)

    print(f"[exporter] HTML → {out}")
    return out

def export_pdf(
    result: RedistributionResult,
    narrative: str = "",
    path: Optional[str] = None,
    output_dir: str = OUTPUT_DIR,
) -> str:
    try:
        from fpdf import FPDF
    except ImportError:
        raise ImportError("fpdf2 is required: pip install fpdf2")

    out = path or os.path.join(_ensure_output_dir(output_dir), "recalibrated_syllabus.pdf")

    pdf = FPDF()
    pdf.add_page()

    # Title
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "Adaptive Syllabus Recalibration Report", ln=True, align="C")
    pdf.ln(5)

    # Narrative
    if narrative:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, "Summary", ln=True)
        pdf.set_font("Helvetica", "", 10)
        pdf.multi_cell(0, 6, narrative)
        pdf.ln(4)

    # Table header
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_fill_color(15, 52, 96)
    pdf.set_text_color(255, 255, 255)
    col_widths = [10, 52, 22, 28, 18, 22, 20, 22]
    headers = ["#", "Module", "Old (h)", "New (h)", "Delta", "PYQ", "Diff", "Importance"]
    for w, h in zip(col_widths, headers):
        pdf.cell(w, 8, h, border=1, fill=True)
    pdf.ln()

    # Table rows
    pdf.set_text_color(0, 0, 0)
    orig_sorted  = sorted(result.original_modules,     key=lambda m: m.module_id)
    recal_sorted = sorted(result.recalibrated_modules, key=lambda m: m.module_id)

    total_orig = total_recal = 0.0
    for i, (orig, recal) in enumerate(zip(orig_sorted, recal_sorted)):
        delta = recal.allocated_hours - orig.original_hours
        total_orig  += orig.original_hours
        total_recal += recal.allocated_hours
        fill = i % 2 == 0
        pdf.set_fill_color(238, 242, 247) if fill else pdf.set_fill_color(255, 255, 255)
        pdf.set_font("Helvetica", "", 9)
        row = [
            str(orig.module_id),
            orig.module_name[:22],
            f"{orig.original_hours:.2f}",
            f"{recal.allocated_hours:.2f}",
            f"{delta:+.2f}",
            f"{orig.pyq_score:.4f}",
            recal.difficulty.value[:4],
            recal.importance.value[:8],
        ]
        for w, val in zip(col_widths, row):
            pdf.cell(w, 7, val, border=1, fill=fill)
        pdf.ln()

    # Totals row
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_fill_color(220, 220, 220)
    pdf.cell(col_widths[0] + col_widths[1], 7, "TOTAL", border=1, fill=True)
    pdf.cell(col_widths[2], 7, f"{total_orig:.2f}", border=1, fill=True)
    pdf.cell(col_widths[3], 7, f"{total_recal:.2f}", border=1, fill=True)
    for w in col_widths[4:]:
        pdf.cell(w, 7, "", border=1, fill=True)
    pdf.ln(10)

    # Warnings
    if result.warnings:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 8, "Warnings", ln=True)
        pdf.set_font("Helvetica", "", 9)
        for w in result.warnings:
            pdf.multi_cell(0, 6, f"  * {w}")

    pdf.output(out)
    print(f"[exporter] PDF -> {out}")
    return out


