"""
exporters.py
------------
Exports RedistributionResult to CSV, HTML, and DOCX.
All files written to ./output/ by default.
"""

from __future__ import annotations

import csv
import os
from typing import List, Optional

from models import Module, RedistributionResult

OUTPUT_DIR = "output"


def _ensure_output_dir(output_dir: str = OUTPUT_DIR) -> str:
    os.makedirs(output_dir, exist_ok=True)
    return output_dir


# ---------------------------------------------------------------------------
# CSV
# ---------------------------------------------------------------------------

def export_csv(
    result: RedistributionResult,
    path: Optional[str] = None,
    output_dir: str = OUTPUT_DIR,
) -> str:
    out = path or os.path.join(_ensure_output_dir(output_dir), "recalibrated_syllabus.csv")
    rows = []
    for orig, recal in zip(
        sorted(result.original_modules, key=lambda m: m.module_id),
        sorted(result.recalibrated_modules, key=lambda m: m.module_id),
    ):
        delta = recal.allocated_hours - orig.original_hours
        rows.append({
            "Module ID":        orig.module_id,
            "Module Name":      orig.module_name,
            "Original Hours":   orig.original_hours,
            "Recalibrated Hours": recal.allocated_hours,
            "Delta (h)":        f"{delta:+.2f}",
            "PYQ Score":        f"{orig.pyq_score:.4f}",
            "Book Weight":      orig.book_weight,
            "Difficulty":       recal.difficulty.value,
            "Importance":       recal.importance.value,
            "Topics":           "; ".join(orig.topics),
        })

    with open(out, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)

    print(f"[exporter] CSV → {out}")
    return out


